USED_EMAILS, USED_PHONES, USED_DOCS = set(), set(), set()


def unique_email(last, first, middle, domain):
    base = translit(last) + "." + translit(first)[:1] + (translit(middle)[:1] if middle else "")
    email, n = f"{base}@{domain}", 1
    while email in USED_EMAILS:
        n += 1
        email = f"{base}{n}@{domain}"
    USED_EMAILS.add(email)
    return email


