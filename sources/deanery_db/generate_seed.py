def weekday_from(d, add_days=0):
    """Ближайший рабочий день (пн–сб) начиная с d + add_days."""
    d = d + dt.timedelta(days=add_days)
    while d.isoweekday() == 7:
        d += dt.timedelta(days=1)
    return d


def friday_of_week(start, week_no):
    monday = start - dt.timedelta(days=start.isoweekday() - 1) + dt.timedelta(weeks=week_no - 1)
    return monday + dt.timedelta(days=4)


