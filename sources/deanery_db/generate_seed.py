    def gen_points(s, disc, sem, stage, attempt="main"):
        key = (disc, sem, stage if attempt == "main" else attempt)
        if key in s.force:
            v = s.force[key]
            return (None, True) if v == "absent" else (v, False)
        t = TYPES[s.type]
        mean = t["mean"] + s.offset + DIFFICULTY[disc]
        absent_p = t["absent"]
        if stage.startswith("module"):
            mean -= 1.5
            absent_p *= 0.5
        if attempt == "retake":
            mean, absent_p = max(mean, 30) + 1.5, absent_p / 2
        elif attempt == "commission":
            mean, absent_p = max(mean, 31) + 2.5, absent_p / 3
        if not s.protect and R.random() < absent_p:
            return None, True
        p = min(round(R.gauss(mean, t["sd"])), 54)
        if s.force_min:
            p = max(p, s.force_min)
        if s.protect:
            p = max(p, 25)
        return (p, False) if p >= 25 else (None, False)

