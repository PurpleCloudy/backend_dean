OUT = []
IDS = collections.Counter()


def lit(v):
    if v is None:
        return "NULL"
    if v is True:
        return "TRUE"
    if v is False:
        return "FALSE"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, dt.datetime):
        return "'" + v.strftime("%Y-%m-%d %H:%M") + "+03'"
    if isinstance(v, dt.date):
        return "'" + v.isoformat() + "'"
    return "'" + str(v).replace("'", "''") + "'"


def sql(text=""):
    OUT.append(text)


def insert(table, cols, rows, comment=None, per_line=1, chunk=600, identity=True):
    """INSERT … VALUES; возвращает сгенерированные идентификаторы (IDENTITY идёт по порядку)."""
    if not rows:
        return []
    if comment:
        sql("-- " + comment)
    for i in range(0, len(rows), chunk):
        part = rows[i:i + chunk]
        lines = []
        for j in range(0, len(part), per_line):
            lines.append(" " + ", ".join("(" + ",".join(lit(v) for v in r) + ")" for r in part[j:j + per_line]))
        sql(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n" + ",\n".join(lines) + ";")
    if not identity:
        return []
    start = IDS[table]
    IDS[table] += len(rows)
    return list(range(start + 1, start + len(rows) + 1))


def one(table, cols, row):
    return insert(table, cols, [row])[0]


